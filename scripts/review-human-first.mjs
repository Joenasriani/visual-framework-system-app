import { readFileSync, writeFileSync } from 'node:fs';
let test = readFileSync('e2e/human-first.mjs','utf8');
const anchor = "  await page.keyboard.press('Escape');\n}";
if (test.split(anchor).length !== 2) throw new Error('Edit helper anchor changed.');
test = test.replace(anchor, "  await page.keyboard.press('Escape');\n  await page.locator('.inspector.panel-open').waitFor({ state: 'hidden' });\n}");
const keyboardAnchor = "  await keys.locator('.frame').focus();\n  await keys.keyboard.press('Enter');\n  await keys.getByLabel('Content', { exact: true }).waitFor();";
if (test.split(keyboardAnchor).length !== 2) throw new Error('Keyboard test anchor changed.');
test = test.replace(keyboardAnchor, `  await keys.locator('.frame').focus();
  await keys.waitForFunction(() => document.activeElement?.classList.contains('frame'));
  console.log('KEYBOARD BEFORE', await keys.evaluate(() => ({ focused: document.activeElement?.outerHTML, editor: document.querySelector('.inspector')?.className })));
  await keys.keyboard.press('Enter');
  await keys.screenshot({ path: \`\${evidence}/06-keyboard-diagnostic.png\` });
  console.log('KEYBOARD AFTER', await keys.evaluate(() => ({ focused: document.activeElement?.outerHTML, editor: document.querySelector('.inspector')?.className, content: document.querySelector('.inspector')?.textContent })));
  await keys.getByLabel('Content', { exact: true }).waitFor();`);
writeFileSync('e2e/human-first.mjs',test);
console.log('Wait for editor closure between keyboard actions and capture exact focus state on reopening.');
